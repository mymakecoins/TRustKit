// Red Test Scaffolder (TASK-005).
// Constitutional Principle I: Strict Hexagonal Isolation.
// Constitutional Principle II: Absolute Prohibition of NULL.
// Constitutional Principle IV: Zero Panic.
// Constitutional Principle VI: Focused Modular Clean Code (< 250 LOC).
// Constitutional Principle VII: Zero Emojis and Zero AI Trailers.

use std::fs;
use std::path::{Path, PathBuf};
use trustkit_core::errors::DomainViolation;

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ScaffoldingTarget {
    pub task_id: String,
    pub target_test_file: String,
    pub criteria_summary: String,
}

pub struct RedTestScaffolder;

impl RedTestScaffolder {
    pub fn scaffold(
        worktree_root: &Path,
        target: &ScaffoldingTarget,
    ) -> Result<PathBuf, DomainViolation> {
        if target.task_id.trim().is_empty() {
            return Err(DomainViolation::AstIntegrityOrInvariantViolation {
                invariant_id: "RN-005".to_string(),
                intercepted_command: "scaffold_red_test".to_string(),
                reason: "task_id cannot be empty".to_string(),
                remediation: "Provide a valid task identifier like TASK-005".to_string(),
            });
        }

        if target.target_test_file.trim().is_empty() {
            return Err(DomainViolation::AstIntegrityOrInvariantViolation {
                invariant_id: "RN-005".to_string(),
                intercepted_command: "scaffold_red_test".to_string(),
                reason: "target_test_file cannot be empty".to_string(),
                remediation: "Provide a relative path for target_test_file".to_string(),
            });
        }

        let full_path = worktree_root.join(&target.target_test_file);

        if full_path.exists() {
            return Ok(full_path);
        }

        if let Some(parent) = full_path.parent() {
            fs::create_dir_all(parent).map_err(|err| {
                DomainViolation::InfrastructureBoundaryFault {
                    subsystem: "red_test_scaffolder".to_string(),
                    details: format!(
                        "Failed to create directory structure for '{}': {}",
                        parent.display(),
                        err
                    ),
                }
            })?;
        }

        let clean_task_id = target.task_id.trim();
        let fn_suffix = clean_task_id.to_lowercase().replace('-', "_");
        let criteria_escaped = target.criteria_summary.replace('"', "\\\"");
        let lower_path = target.target_test_file.to_ascii_lowercase();

        let scaffolded_content = if lower_path.ends_with(".ts")
            || lower_path.ends_with(".tsx")
            || lower_path.ends_with(".js")
            || lower_path.ends_with(".mjs")
        {
            let pkg_raw =
                fs::read_to_string(worktree_root.join("package.json")).unwrap_or_default();
            if pkg_raw.contains("\"vitest\"") {
                format!(
                    "// Integration test for {clean_task_id}.\n\
                     // Generated by RedTestScaffolder (TASK-005).\n\
                     import {{ describe, it, expect }} from 'vitest';\n\n\
                     describe('{clean_task_id}', () => {{\n\
                       it('red phase contract', () => {{\n\
                         // Criterios: \"{criteria_escaped}\"\n\
                         throw new Error('TASK RED ASSERTION: {clean_task_id} not implemented yet');\n\
                       }});\n\
                     }});\n"
                )
            } else if pkg_raw.contains("\"jest\"") {
                format!(
                    "// Integration test for {clean_task_id}.\n\
                     // Generated by RedTestScaffolder (TASK-005).\n\
                     describe('{clean_task_id}', () => {{\n\
                       it('red phase contract', () => {{\n\
                         // Criterios: \"{criteria_escaped}\"\n\
                         throw new Error('TASK RED ASSERTION: {clean_task_id} not implemented yet');\n\
                       }});\n\
                     }});\n"
                )
            } else {
                format!(
                    "// Integration test for {clean_task_id}.\n\
                     // Generated by RedTestScaffolder (TASK-005).\n\
                     import test from 'node:test';\n\
                     import assert from 'node:assert/strict';\n\n\
                     test('{clean_task_id} red phase contract', () => {{\n\
                       // Criterios: \"{criteria_escaped}\"\n\
                       assert.fail('TASK RED ASSERTION: {clean_task_id} not implemented yet');\n\
                     }});\n"
                )
            }
        } else if lower_path.ends_with(".py") {
            format!(
                "# Integration test for {clean_task_id}.\n\
                 # Generated by RedTestScaffolder (TASK-005).\n\n\
                 def test_{fn_suffix}_red_phase_contract():\n\
                     # Criterios: \"{criteria_escaped}\"\n\
                     assert False, \"TASK RED ASSERTION: {clean_task_id} not implemented yet\"\n"
            )
        } else if lower_path.ends_with(".go") {
            format!(
                "// Integration test for {clean_task_id}.\n\
                 package tests\n\n\
                 import \"testing\"\n\n\
                 func Test_{fn_suffix}(t *testing.T) {{\n\
                     // Criterios: \"{criteria_escaped}\"\n\
                     t.Fatalf(\"TASK RED ASSERTION: {clean_task_id} not implemented yet\")\n\
                 }}\n"
            )
        } else {
            format!(
                r#"// Integration test for {clean_task_id}.
// Generated by RedTestScaffolder (TASK-005).
// Constitutional Principle VII: Zero Emojis and Zero AI Trailers.

#[test]
fn test_{fn_suffix}_red_phase_contract() {{
    // Criterios: "{criteria_escaped}"
    panic!("TASK RED ASSERTION: {clean_task_id} not implemented yet");
}}
"#
            )
        };

        fs::write(&full_path, scaffolded_content).map_err(|err| {
            DomainViolation::InfrastructureBoundaryFault {
                subsystem: "red_test_scaffolder".to_string(),
                details: format!(
                    "Failed to write scaffolded test file '{}': {}",
                    full_path.display(),
                    err
                ),
            }
        })?;

        Ok(full_path)
    }
}
