use std::fs;
use std::path::{Path, PathBuf};
use trustkit_core::errors::DomainViolation;

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ScaffoldingTarget {
    pub task_id: String,
    pub target_test_file: String,
    pub criteria_summary: String,
}

pub struct RedTestScaffolder;

impl RedTestScaffolder {
    pub fn scaffold(
        worktree_root: &Path,
        target: &ScaffoldingTarget,
    ) -> Result<PathBuf, DomainViolation> {
        if target.task_id.trim().is_empty() {
            return Err(DomainViolation::AstIntegrityOrInvariantViolation {
                invariant_id: "RN-005".to_string(),
                intercepted_command: "scaffold_red_test".to_string(),
                reason: "task_id cannot be empty".to_string(),
                remediation: "Provide a valid task identifier like TASK-005".to_string(),
            });
        }

        if target.target_test_file.trim().is_empty() {
            return Err(DomainViolation::AstIntegrityOrInvariantViolation {
                invariant_id: "RN-005".to_string(),
                intercepted_command: "scaffold_red_test".to_string(),
                reason: "target_test_file cannot be empty".to_string(),
                remediation: "Provide a relative path for target_test_file".to_string(),
            });
        }

        let full_path = worktree_root.join(&target.target_test_file);

        if full_path.exists() {
            return Ok(full_path);
        }

        if let Some(parent) = full_path.parent() {
            fs::create_dir_all(parent).map_err(|err| {
                DomainViolation::InfrastructureBoundaryFault {
                    subsystem: "red_test_scaffolder".to_string(),
                    details: format!(
                        "Failed to create directory structure for '{}': {}",
                        parent.display(),
                        err
                    ),
                }
            })?;
        }

        let clean_task_id = target.task_id.trim();
        let fn_suffix = clean_task_id.to_lowercase().replace('-', "_");
        let criteria_escaped = target.criteria_summary.replace('"', "\\\"");

        let scaffolded_content = format!(
            r#"// Integration test for {clean_task_id}.
// Generated by RedTestScaffolder (TASK-005).
// Constitutional Principle VII: Zero Emojis and Zero AI Trailers.

#[test]
fn test_{fn_suffix}_red_phase_contract() {{
    // Criterios: "{criteria_escaped}"
    panic!("TASK RED ASSERTION: {clean_task_id} not implemented yet");
}}
"#
        );

        fs::write(&full_path, scaffolded_content).map_err(|err| {
            DomainViolation::InfrastructureBoundaryFault {
                subsystem: "red_test_scaffolder".to_string(),
                details: format!(
                    "Failed to write scaffolded test file '{}': {}",
                    full_path.display(),
                    err
                ),
            }
        })?;

        Ok(full_path)
    }
}
