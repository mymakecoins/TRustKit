use std::fs;
use std::path::{Path, PathBuf};

fn workspace_root() -> PathBuf {
    let manifest_dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    manifest_dir
        .ancestors()
        .find(|p| p.join("Cargo.lock").exists())
        .unwrap_or(manifest_dir)
        .to_path_buf()
}

fn is_emoji(c: char) -> bool {
    matches!(c,
        '\u{1F600}'..='\u{1F64F}' | // Emoticons
        '\u{1F300}'..='\u{1F5FF}' | // Misc Symbols and Pictographs
        '\u{1F680}'..='\u{1F6FF}' | // Transport and Map
        '\u{1F1E0}'..='\u{1F1FF}' | // Regional indicator symbols
        '\u{2600}'..='\u{26FF}'   | // Misc symbols
        '\u{2700}'..='\u{27BF}'   | // Dingbats
        '\u{FE00}'..='\u{FE0F}'   | // Variation Selectors
        '\u{1F900}'..='\u{1F9FF}' | // Supplemental Symbols and Pictographs
        '\u{1FA70}'..='\u{1FAFF}'   // Symbols and Pictographs Extended-A
    )
}

fn assert_zero_emojis(path: &str, content: &str) {
    for (line_idx, line) in content.lines().enumerate() {
        for ch in line.chars() {
            assert!(
                !is_emoji(ch),
                "Forbidden emoji '{ch}' found in {path} at line {line_idx}: {line}"
            );
        }
    }
}

fn assert_zero_ai_trailers(path: &str, content: &str) {
    for (line_idx, line) in content.lines().enumerate() {
        let trimmed = line.trim();
        if trimmed.starts_with("Co-Authored-By:")
            || trimmed.starts_with("co-authored-by:")
            || trimmed.starts_with("Generated by Claude")
            || trimmed.starts_with("Generated by GPT")
        {
            panic!("AI trailer found in {path} at line {line_idx}: {line}");
        }
    }
}

#[test]
fn test_readme_documents_milestones_and_init_option() {
    let root = workspace_root();
    let file_path = root.join("README.md");
    assert!(file_path.exists(), "README.md must exist");
    let content = fs::read_to_string(&file_path).expect("Failed to read README.md");

    assert!(
        content.contains("trustkit milestones plan"),
        "README.md must document 'trustkit milestones plan'"
    );
    assert!(
        content.contains("trustkit milestones list"),
        "README.md must document 'trustkit milestones list'"
    );
    assert!(
        content.contains("trustkit milestones inspect"),
        "README.md must document 'trustkit milestones inspect'"
    );
    assert!(
        content.contains("--milestone"),
        "README.md must document the '--milestone' option for trustkit init"
    );

    assert_zero_emojis("README.md", &content);
    assert_zero_ai_trailers("README.md", &content);
}

