use std::fs;
use std::path::{Path, PathBuf};

fn workspace_root() -> PathBuf {
    let manifest_dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    manifest_dir
        .ancestors()
        .find(|p| p.join("Cargo.lock").exists())
        .unwrap_or(manifest_dir)
        .to_path_buf()
}

fn assert_zero_emojis(path: &str, content: &str) {
    for (line_idx, line) in content.lines().enumerate() {
        for ch in line.chars() {
            assert!(
                !is_emoji(ch),
                "Forbidden emoji '{ch}' found in {path} at line {line_idx}: {line}"
            );
        }
    }
}

fn is_emoji(c: char) -> bool {
    matches!(c,
        '\u{1F600}'..='\u{1F64F}' |
        '\u{1F300}'..='\u{1F5FF}' |
        '\u{1F680}'..='\u{1F6FF}' |
        '\u{1F1E0}'..='\u{1F1FF}' |
        '\u{2600}'..='\u{26FF}'   |
        '\u{2700}'..='\u{27BF}'   |
        '\u{FE00}'..='\u{FE0F}'   |
        '\u{1F900}'..='\u{1F9FF}' |
        '\u{1FA70}'..='\u{1FAFF}'
    )
}

fn assert_zero_ai_trailers(path: &str, content: &str) {
    for (line_idx, line) in content.lines().enumerate() {
        let trimmed = line.trim();
        if trimmed.starts_with("Co-Authored-By:")
            || trimmed.starts_with("co-authored-by:")
            || trimmed.starts_with("Generated by")
        {
            panic!("AI trailer found in {path} at line {line_idx}: {line}");
        }
    }
}

#[test]
fn test_task_004_skills_document_tk_alias() {
    let root = workspace_root();
    let skill_paths = [
        root.join("skills/trustkit-sdd/SKILL.md"),
        root.join(".agents/skills/trustkit-sdd/SKILL.md"),
    ];

    for path in &skill_paths {
        let content = fs::read_to_string(path)
            .unwrap_or_else(|e| panic!("Failed reading skill at {:?}: {e}", path));
        let path_str = path.to_string_lossy();
        assert_zero_emojis(&path_str, &content);
        assert_zero_ai_trailers(&path_str, &content);
        assert!(
            content.contains("alias `tk`") || content.contains("alias 'tk'"),
            "Skill at {:?} must document the 'tk' alias explicitly",
            path
        );
    }
}
