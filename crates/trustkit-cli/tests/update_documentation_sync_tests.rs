use std::fs;
use std::path::{Path, PathBuf};

fn workspace_root() -> PathBuf {
    let manifest_dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    manifest_dir
        .ancestors()
        .find(|p| p.join("Cargo.lock").exists())
        .unwrap_or(manifest_dir)
        .to_path_buf()
}

fn is_emoji(c: char) -> bool {
    matches!(
        c,
        '\u{1F600}'..='\u{1F64F}'
            | '\u{1F300}'..='\u{1F5FF}'
            | '\u{1F680}'..='\u{1F6FF}'
            | '\u{1F1E0}'..='\u{1F1FF}'
            | '\u{2600}'..='\u{26FF}'
            | '\u{2700}'..='\u{27BF}'
            | '\u{FE00}'..='\u{FE0F}'
            | '\u{1F900}'..='\u{1F9FF}'
            | '\u{1FA70}'..='\u{1FAFF}'
    )
}

#[test]
fn test_docs_and_skills_document_update_command_without_emojis() {
    let root = workspace_root();
    let files = [
        "README.md",
        "docs/manual/MANUAL_DO_USUARIO.md",
        "skills/trustkit-sdd/SKILL.md",
        ".agents/skills/trustkit-sdd/SKILL.md",
    ];

    for rel in files {
        let content =
            fs::read_to_string(root.join(rel)).unwrap_or_else(|e| panic!("Read {rel}: {e}"));
        assert!(
            content.contains("trustkit update"),
            "{rel} must document 'trustkit update'"
        );
        assert!(
            content.contains("tk update --check"),
            "{rel} must document 'tk update --check'"
        );
        assert!(
            content.contains("tk update"),
            "{rel} must document 'tk update'"
        );
        for (line_idx, line) in content.lines().enumerate() {
            for ch in line.chars() {
                assert!(
                    !is_emoji(ch),
                    "Forbidden emoji '{ch}' found in {rel} at line {line_idx}"
                );
            }
            let trimmed = line.trim();
            assert!(
                !trimmed.starts_with("Co-Authored-By:")
                    && !trimmed.starts_with("co-authored-by:")
                    && !trimmed.starts_with("Generated by"),
                "Forbidden AI trailer found in {rel} at line {line_idx}"
            );
        }
    }
}
