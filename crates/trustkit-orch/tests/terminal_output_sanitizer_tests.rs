use trustkit_orch::terminal_output_sanitizer::TerminalOutputSanitizer;

#[test]
fn test_strip_ansi_escapes() {
    let raw = "\x1b[32mPASS\x1b[0m: Test ran \x1b[1;34msuccessfully\x1b[0m\r\n";
    let stripped = TerminalOutputSanitizer::strip_ansi_escapes(raw);
    assert_eq!(stripped, "PASS: Test ran successfully\n");
}

#[test]
fn test_purge_emojis_and_icons() {
    let raw = "Status: PASS 🚀 Done! ✨ Checkmark ✔️";
    let purged = TerminalOutputSanitizer::purge_emojis_and_icons(raw);
    assert!(!purged.contains('🚀'));
    assert!(!purged.contains('✨'));
    assert!(purged.contains("Status: PASS"));
    assert!(purged.contains("Done!"));
}

#[test]
fn test_purge_ai_trailers() {
    let raw = "Commit message\nCo-Authored-By: Claude <claude@anthropic.com>\nGenerated by Claude Code\nFinal line\n";
    let purged = TerminalOutputSanitizer::purge_ai_trailers(raw);
    assert!(!purged.contains("Co-Authored-By"));
    assert!(!purged.contains("Generated by"));
    assert!(purged.contains("Commit message"));
    assert!(purged.contains("Final line"));
}

#[test]
fn test_redact_secrets() {
    let raw = "Using token ghp_1234567890abcdef1234567890 and Bearer eyJhbGciOiJIUzI1NiJ9.test";
    let redacted = TerminalOutputSanitizer::redact_secrets(raw);
    assert!(!redacted.contains("ghp_1234567890abcdef"));
    assert!(redacted.contains("[REDACTED_SECRET]"));
}

#[test]
fn test_sanitize_terminal_buffer_pipeline() {
    let raw =
        "\x1b[32m✔\x1b[0m Done 🚀\nghp_1234567890abcdef1234567890\nCo-Authored-By: AI\nAll good.\n";
    let sanitized = TerminalOutputSanitizer::sanitize(raw);
    assert!(!sanitized.contains('🚀'));
    assert!(!sanitized.contains("Co-Authored-By"));
    assert!(!sanitized.contains("ghp_"));
    assert!(sanitized.contains("[REDACTED_SECRET]"));
    assert!(sanitized.contains("All good."));
}
