// Terminal Output Sanitizer for VT buffer cleaning and constitutional compliance.
// Constitutional Principle I: Strict Hexagonal Isolation.
// Constitutional Principle IV: Zero Panic.
// Constitutional Principle VI: Focused Modular Clean Code (< 250 LOC).
// Constitutional Principle VII: Zero Emojis and Zero AI Trailers.

use regex::Regex;
use std::sync::LazyLock;
use crate::async_supervisor::redact_secrets;

static ANSI_REGEX: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(r"\x1B(?:[@-Z\\-_]|\[[0-?]*[ -/]*[@-~]|\][^\x07\x1B]*(?:\x07|\x1B\\))").unwrap()
});

static AI_TRAILER_PATTERNS: LazyLock<Vec<Regex>> = LazyLock::new(|| {
    vec![
        Regex::new(r"(?i)^\s*co-authored-by:.*$").unwrap(),
        Regex::new(r"(?i)^\s*generated by.*$").unwrap(),
        Regex::new(r"(?i)^\s*authored[- ]by[- ]ai:.*$").unwrap(),
    ]
});

pub struct TerminalOutputSanitizer;

impl TerminalOutputSanitizer {
    pub fn strip_ansi_escapes(raw: &str) -> String {
        let stripped = ANSI_REGEX.replace_all(raw, "").to_string();
        stripped.replace("\r\n", "\n").replace('\r', "")
    }

    pub fn purge_emojis_and_icons(text: &str) -> String {
        text.chars()
            .filter(|&c| !is_emoji_or_icon(c))
            .collect()
    }

    pub fn purge_ai_trailers(text: &str) -> String {
        let mut lines = Vec::new();
        for line in text.lines() {
            let is_trailer = AI_TRAILER_PATTERNS.iter().any(|re| re.is_match(line));
            if !is_trailer {
                lines.push(line);
            }
        }
        let mut out = lines.join("\n");
        if text.ends_with('\n') {
            out.push('\n');
        }
        out
    }

    pub fn redact_secrets(text: &str) -> String {
        redact_secrets(text)
    }

    pub fn sanitize(raw: &str) -> String {
        let no_ansi = Self::strip_ansi_escapes(raw);
        let no_emojis = Self::purge_emojis_and_icons(&no_ansi);
        let no_trailers = Self::purge_ai_trailers(&no_emojis);
        Self::redact_secrets(&no_trailers)
    }
}

fn is_emoji_or_icon(c: char) -> bool {
    matches!(
        c,
        '\u{1F600}'..='\u{1F64F}' | // Emoticons
        '\u{1F300}'..='\u{1F5FF}' | // Misc Symbols and Pictographs
        '\u{1F680}'..='\u{1F6FF}' | // Transport and Map
        '\u{1F700}'..='\u{1F77F}' | // Alchemical
        '\u{1F780}'..='\u{1F7FF}' | // Geometric Shapes Extended
        '\u{1F800}'..='\u{1F8FF}' | // Supplemental Arrows-C
        '\u{1F900}'..='\u{1F9FF}' | // Supplemental Symbols and Pictographs
        '\u{1FA00}'..='\u{1FA6F}' | // Chess Symbols
        '\u{1FA70}'..='\u{1FAFF}' | // Symbols and Pictographs Extended-A
        '\u{2600}'..='\u{26FF}'   | // Misc Symbols
        '\u{2700}'..='\u{27BF}'   | // Dingbats
        '\u{FE00}'..='\u{FE0F}'     // Variation Selectors
    )
}
